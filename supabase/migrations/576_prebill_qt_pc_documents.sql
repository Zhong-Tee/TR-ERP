-- QT/PC: sales documents that exist before a real order is created.
-- They intentionally live outside or_orders so they cannot enter WMS/QC/accounting flows.

CREATE TABLE IF NOT EXISTS public.or_prebill_channel_settings (
  channel_code TEXT NOT NULL REFERENCES public.channels(channel_code) ON UPDATE CASCADE ON DELETE CASCADE,
  document_type TEXT NOT NULL CHECK (document_type IN ('quotation', 'production_confirmation')),
  document_prefix TEXT NOT NULL,
  header_name TEXT NOT NULL,
  default_valid_days INTEGER NOT NULL DEFAULT 7 CHECK (default_valid_days BETWEEN 1 AND 365),
  updated_by UUID REFERENCES public.us_users(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (channel_code, document_type)
);

CREATE TABLE IF NOT EXISTS public.or_prebill_number_sequences (
  channel_code TEXT NOT NULL,
  document_type TEXT NOT NULL CHECK (document_type IN ('quotation', 'production_confirmation')),
  period CHAR(4) NOT NULL,
  last_number INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (channel_code, document_type, period)
);

CREATE TABLE IF NOT EXISTS public.or_prebill_documents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  document_type TEXT NOT NULL CHECK (document_type IN ('quotation', 'production_confirmation')),
  document_no TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN (
    'draft', 'active', 'pending_discount', 'approved', 'rejected',
    'expired', 'converted', 'cancelled'
  )),
  channel_code TEXT NOT NULL REFERENCES public.channels(channel_code) ON UPDATE CASCADE,
  header_name TEXT NOT NULL,
  customer_name TEXT NOT NULL DEFAULT 'ลูกค้า',
  customer_address TEXT,
  recipient_name TEXT,
  customer_phone TEXT,
  billing_details JSONB NOT NULL DEFAULT '{}'::jsonb,
  delivery_term TEXT NOT NULL DEFAULT '1-3 วัน',
  valid_until DATE NOT NULL,
  payment_method TEXT,
  subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
  shipping_cost NUMERIC(14,2) NOT NULL DEFAULT 0,
  promotion_discount NUMERIC(14,2) NOT NULL DEFAULT 0,
  special_discount NUMERIC(14,2) NOT NULL DEFAULT 0,
  special_discount_type TEXT CHECK (special_discount_type IS NULL OR special_discount_type IN ('amount', 'percent')),
  special_discount_value NUMERIC(14,2) NOT NULL DEFAULT 0,
  total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
  promotion_ids UUID[] NOT NULL DEFAULT '{}'::uuid[],
  promotion_snapshot JSONB NOT NULL DEFAULT '[]'::jsonb,
  shipping_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
  internal_note TEXT,
  discount_request_note TEXT,
  discount_requested_at TIMESTAMPTZ,
  discount_requested_by UUID REFERENCES public.us_users(id) ON DELETE SET NULL,
  approved_special_discount NUMERIC(14,2),
  approval_note TEXT,
  approved_at TIMESTAMPTZ,
  approved_by UUID REFERENCES public.us_users(id) ON DELETE SET NULL,
  rejection_note TEXT,
  converted_order_id UUID UNIQUE REFERENCES public.or_orders(id) ON DELETE SET NULL,
  converted_at TIMESTAMPTZ,
  source_document_id UUID REFERENCES public.or_prebill_documents(id) ON DELETE SET NULL,
  owner_id UUID NOT NULL REFERENCES public.us_users(id) ON DELETE RESTRICT DEFAULT auth.uid(),
  owner_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT or_prebill_non_negative CHECK (
    subtotal >= 0 AND shipping_cost >= 0 AND promotion_discount >= 0
    AND special_discount >= 0 AND special_discount_value >= 0 AND total_amount >= 0
  )
);

